import fs from "node:fs";
import path from "node:path";

const root = path.join(process.cwd(), "memory_bank");
const indexedFolders = ["architecture", "decisions", "meetings", "prompts"];
const typeOrder = new Map(["decision", "architecture", "prompt", "meeting"].map((type, index) => [type, index]));
const checkOnly = process.argv.includes("--check");

function writeOrCheck(filename, content) {
  if (!checkOnly) {
    fs.writeFileSync(filename, content, "utf8");
    return;
  }
  if (!fs.existsSync(filename) || fs.readFileSync(filename, "utf8") !== content) {
    throw new Error(`${path.relative(process.cwd(), filename)} is stale. Run npm run memory:index.`);
  }
}

function parseNote(folder, filename) {
  const content = fs.readFileSync(path.join(root, folder, filename), "utf8");
  const frontmatter = content.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!frontmatter) throw new Error(`${folder}/${filename} has no frontmatter.`);
  const values = Object.fromEntries(frontmatter[1].split(/\r?\n/).map((line) => {
    const separator = line.indexOf(":");
    return separator < 0 ? [line, ""] : [line.slice(0, separator).trim(), line.slice(separator + 1).trim()];
  }));
  const title = content.match(/^#\s+(.+)$/m)?.[1]?.trim();
  if (!values.id || !values.type || !values.updated || !title) throw new Error(`${folder}/${filename} has incomplete indexed metadata.`);
  let relatedTasks = values.related_tasks ?? "[]";
  try {
    relatedTasks = JSON.parse(relatedTasks).join(", ");
  } catch {
    relatedTasks = relatedTasks.replace(/^\[|\]$/g, "").replaceAll('"', "");
  }
  return {
    folder,
    filename,
    id: values.id,
    type: values.type,
    title,
    phase: values.phase ?? "",
    relatedTasks,
    status: values.status ?? "",
    updated: values.updated,
  };
}

function compareNotes(left, right) {
  return right.updated.localeCompare(left.updated)
    || (typeOrder.get(left.type) ?? 99) - (typeOrder.get(right.type) ?? 99)
    || right.id.localeCompare(left.id);
}

function table(notes, scoped = false) {
  const rows = notes.map((note) => `| ${note.type} | ${note.id} | ${note.title} | ${note.phase} | ${note.relatedTasks} | ${note.status} | ${note.updated} | [open](${scoped ? note.filename : `${note.folder}/${note.filename}`}) |`);
  return [
    "| type | id | title | phase | related_tasks | status | updated | link |",
    "|---|---|---|---:|---|---|---|---|",
    ...rows,
  ].join("\n");
}

const notes = indexedFolders.flatMap((folder) => fs.readdirSync(path.join(root, folder))
  .filter((filename) => filename.endsWith(".md") && filename !== "_index.md")
  .map((filename) => parseNote(folder, filename))).sort(compareNotes);

const master = `# Agent OS Memory Bank Index

Generated by \`npm run memory:index\` from indexed note frontmatter. Do not edit manually.

## Task Start

1. Read [Current Context](architecture/current-context.md).
2. Open only the relevant decision or tracker from the index below.
3. Verify memory claims against current code and tests before editing.

${table(notes)}

## Phase Trackers

- [Phase 1](todos/phase-1.md)
- [Phase 2](todos/phase-2.md)
- [Phase 3](todos/phase-3.md)
- [Phase 4](todos/phase-4.md)
`;
writeOrCheck(path.join(root, "index.md"), master);

for (const folder of indexedFolders) {
  const folderNotes = notes.filter((note) => note.folder === folder);
  const title = `${folder[0].toUpperCase()}${folder.slice(1)} Index`;
  const content = `# ${title}\n\nGenerated by \`npm run memory:index\` from note frontmatter. Do not edit manually.\n\n${folderNotes.length ? table(folderNotes, true) : "No indexed notes recorded."}\n`;
  writeOrCheck(path.join(root, folder, "_index.md"), content);
}

console.log(`${checkOnly ? "Verified" : "Indexed"} ${notes.length} memory-bank notes.`);